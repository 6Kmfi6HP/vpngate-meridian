def save_json_atomic(data: Any, path: str) -> None:
    """Write *data* as JSON to *path* using an atomic temp-file + rename."""
    dirpath = os.path.dirname(path) or '.'
    os.makedirs(dirpath, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        'w', delete=False, dir=dirpath, encoding='utf-8',
    ) as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write('\n')
        temp_path = f.name
    os.replace(temp_path, path)
    logger.info('Output saved to %s', path)


def save_text_atomic(text: str, path: str) -> None:
    """Write *text* to *path* using an atomic temp-file + rename."""
    dirpath = os.path.dirname(path) or '.'
    os.makedirs(dirpath, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        'w', delete=False, dir=dirpath, encoding='utf-8',
    ) as f:
        f.write(text)
        temp_path = f.name
    os.replace(temp_path, path)
    logger.info('Output saved to %s', path)


# ---------------------------------------------------------------------------
# Batch processing
# ---------------------------------------------------------------------------

def run_batch(
    batch_proxies: List[Dict[str, Any]],
    batch_index: int,
    image: str,
    controller_port: int,
    mixed_port: int,
    batch_timeout: int,
) -> Dict[str, int]:
    """Run a single batch of proxies through an ephemeral mihomo container.

    Returns ``{proxy_name: latency_ms}`` for proxies that responded.
    The container is always cleaned up (try/finally).
    """
    config_yaml = render_batch_config(
        batch_proxies, controller_port, mixed_port,
    )
    container_name: Optional[str] = None
    temp_dir: Optional[str] = None

    try:
        # Write the config to a temporary file that will be mounted into the
        # container.
        temp_dir = tempfile.mkdtemp(prefix='mihomo-batch-')
        config_path = os.path.join(temp_dir, 'config.yaml')
        with open(config_path, 'w', encoding='utf-8') as f:
            f.write(config_yaml)

        _, container_name = start_mihomo_container(
            config_path, batch_index, image, controller_port,
        )

        if not wait_for_api(controller_port, timeout=batch_timeout):
            logger.warning(
                'Batch %d: API did not become ready, skipping',
                batch_index,
            )
            return {}

        results = run_delay_test(controller_port, timeout=batch_timeout)
        if results is None:
            logger.warning(
                'Batch %d: delay test produced no results',
                batch_index,
            )
            return {}

        return results

    finally:
        if container_name is not None:
            stop_mihomo_container(container_name)
        if temp_dir is not None:
            shutil.rmtree(temp_dir, ignore_errors=True)


def process_all_proxies(
    proxies: List[Dict[str, Any]],
    batch_size: int,
    image: str,
    controller_port: int,
    mixed_port: int,
    batch_timeout: int,
) -> Dict[str, int]:
    """Test all *proxies* in batches, returning ``{name: latency_ms}``."""
    all_results: Dict[str, int] = {}
    total_batches = math.ceil(len(proxies) / batch_size)

    for batch_idx in range(total_batches):
        start = batch_idx * batch_size
        end = min(start + batch_size, len(proxies))
        batch = proxies[start:end]

        logger.info(
            'Batch %d/%d: testing %d proxies (indices %d-%d)',
            batch_idx + 1, total_batches, len(batch), start, end - 1,
        )

        results = run_batch(
            batch, batch_idx,
            image, controller_port, mixed_port, batch_timeout,
        )
        all_results.update(results)

        alive_so_far = len(all_results)
        tested_so_far = min(end, len(proxies))
        pct = (
            alive_so_far / tested_so_far * 100
            if tested_so_far > 0 else 0.0
        )
        logger.info(
            'Progress: %d/%d alive (%.1f%%)',
            alive_so_far, tested_so_far, pct,
        )

    return all_results


