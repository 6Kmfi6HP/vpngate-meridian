# Main
# ---------------------------------------------------------------------------

def main(argv: Optional[List[str]] = None) -> None:
    """Entry point for ``scripts/test_openvpn.py``."""
    args = parse_args(argv)

    # -- Docker availability check -----------------------------------------
    if not check_docker():
        logger.warning(
            'Docker is not available or the daemon is not running. '
            'Skipping OpenVPN testing.',
        )
        sys.exit(0)

    # -- Read input files --------------------------------------------------
    logger.info('Reading mihomo YAML from %s', args.mihomo_input)
    with open(args.mihomo_input, 'r', encoding='utf-8') as f:
        yaml_text = f.read()

    proxies = parse_mihomo_proxies(yaml_text)
    logger.info('Parsed %d proxies from mihomo YAML', len(proxies))

    if not proxies:
        logger.warning('No proxies found in mihomo YAML. Nothing to test.')
        sys.exit(0)

    logger.info('Reading VPN Gate data from %s', args.data_input)
    with open(args.data_input, 'r', encoding='utf-8') as f:
        vpn_data = json.load(f)

    servers: List[Dict[str, Any]] = (
        vpn_data.get('data', {}).get('servers', [])
    )
    logger.info('Loaded %d servers from data.json', len(servers))

    # -- Build proxy-name to server-index mapping --------------------------
    proxy_names = [p['name'] for p in proxies]
    proxy_to_server = build_proxy_to_server_map(servers, proxy_names)

    # -- Run tests ---------------------------------------------------------
    results = process_all_proxies(
        proxies,
        batch_size=args.batch_size,
        image=args.docker_image,
        controller_port=args.controller_port,
        mixed_port=args.mixed_port,
        batch_timeout=args.batch_timeout,
    )
    logger.info(
        'Testing complete: %d proxies alive out of %d',
        len(results), len(proxies),
    )

    # -- Timestamp ---------------------------------------------------------
    now_iso = (
        datetime.now(timezone.utc)
        .isoformat(timespec='milliseconds')
        .replace('+00:00', 'Z')
    )

    # -- Annotate servers --------------------------------------------------
    all_delays: List[int] = []

    # Mark alive servers
    for proxy_name, delay in results.items():
        server_idx = proxy_to_server.get(proxy_name)
        if server_idx is None:
            logger.debug(
                'Skipping annotation for unmatched proxy: %s', proxy_name,
            )
            continue
        servers[server_idx]['test'] = {
            'alive': True,
            'latencyMs': delay,
            'testedAt': now_iso,
        }
        all_delays.append(delay)

    # Mark tested-but-dead servers
    tested_names = set(results.keys())
    for proxy_name in proxy_names:
        if proxy_name in tested_names:
            continue
        server_idx = proxy_to_server.get(proxy_name)
        if server_idx is None:
            continue
        servers[server_idx]['test'] = {
            'alive': False,
            'latencyMs': None,
            'testedAt': now_iso,
        }

    # -- Statistics --------------------------------------------------------
    stats = compute_statistics(all_delays, len(proxies))

    # -- Top-level test metadata in data.json ------------------------------
    vpn_data['test'] = {
        'generatedAt': now_iso,
        'statistics': stats,
    }

    # -- Save outputs ------------------------------------------------------

    # 1. Tested data.json
    save_json_atomic(vpn_data, args.tested_data)

    # 2. Results JSON (includes both summary and per-proxy details)
    results_data: Dict[str, Any] = {
        'generatedAt': now_iso,
        'statistics': stats,
        'results': [
            {'proxyName': name, 'latencyMs': delay}
            for name, delay in sorted(
                results.items(), key=lambda x: x[1],
            )
        ],
    }
    save_json_atomic(results_data, args.results_json)

    # 3. Alive mihomo YAML (sorted by latency, limited to max-alive)
    alive_with_latency: List[Tuple[Dict[str, Any], int]] = []
    for proxy in proxies:
        pname = proxy['name']
        if pname in results:
            alive_with_latency.append((proxy, results[pname]))
    alive_with_latency.sort(key=lambda x: x[1])
    alive_with_latency = alive_with_latency[:args.max_alive]

    alive_yaml = render_alive_yaml(alive_with_latency)
    save_text_atomic(alive_yaml, args.alive_mihomo)

    # -- Summary to log ----------------------------------------------------
    logger.info(
        'Results: %d total, %d alive, %d dead (%.1f%% alive rate)',
        stats['total'], stats['alive'], stats['dead'], stats['aliveRate'],
    )
    if all_delays:
        logger.info(
            'Latency: avg=%.0fms  p50=%dms  p90=%dms',
            stats['avgLatency'], stats['p50Latency'], stats['p90Latency'],
        )


if __name__ == '__main__':
    main()
