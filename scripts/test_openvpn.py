def _parse_yaml_scalar(value: str) -> Any:
    """Parse a single YAML scalar string into a Python value.

    Handles quoted strings, booleans, null, and numeric types.
    """
    if not value:
        return value
    if value.startswith('"') and value.endswith('"'):
        return json.loads(value)
    if value.startswith("'") and value.endswith("'"):
        return value[1:-1]
    if value in ('true', 'True', 'TRUE'):
        return True
    if value in ('false', 'False', 'FALSE'):
        return False
    if value in ('null', 'Null', 'NULL', '~'):
        return None
    try:
        return int(value)
    except ValueError:
        try:
            return float(value)
        except ValueError:
            return value


def _find_colon_split(line: str) -> Optional[Tuple[str, str]]:
    """Split *line* on the first ``:`` and return ``(key, rest)``.

    Returns ``None`` when no colon is found.
    """
    colon = line.find(':')
    if colon < 0:
        return None
    return line[:colon].strip(), line[colon + 1:].strip()


def parse_mihomo_proxies(text: str) -> List[Dict[str, Any]]:
    """Parse the YAML proxy list generated by ``render_mihomo_yaml``.

    The expected format is::

        proxies:
          - name: "JP AS2516 ..."
            type: "openvpn"
            server: "203.0.113.10"
            port: 443
            ca: |-
              -----BEGIN CERTIFICATE-----
              ...
              -----END CERTIFICATE-----
            ...

    Multiline block scalars (indicated by ``|-``) are continued on lines
    indented with exactly 6 spaces.
    """
    lines = text.splitlines()
    proxies: List[Dict[str, Any]] = []
    proxy: Optional[Dict[str, Any]] = None
    multiline_key: Optional[str] = None

    def _close_multiline() -> None:
        """Finalise the current multiline value (strip trailing newline)."""
        nonlocal multiline_key
        if multiline_key is not None and proxy is not None:
            val = proxy.get(multiline_key, '')
            if val and val[-1] == '\n':
                proxy[multiline_key] = val.rstrip('\n')
            multiline_key = None

    idx = 0
    while idx < len(lines):
        raw = lines[idx]
        line = raw.rstrip()
        leading = len(raw) - len(raw.lstrip())

        # -- empty lines ---------------------------------------------------
        if not line:
            if multiline_key is not None and proxy is not None:
                proxy[multiline_key] += '\n'
            idx += 1
            continue

        # -- comment lines (inline or full-line) ---------------------------
        if line.lstrip().startswith('#'):
            idx += 1
            continue

        # -- top-level keys (no leading whitespace) ------------------------
        if leading == 0:
            idx += 1
            continue

        # -- proxy list item start: "  - " ---------------------------------
        if line.startswith('  - '):
            _close_multiline()
            if proxy is not None:
                proxies.append(proxy)
            proxy = {}
            kv = _find_colon_split(line[4:])
            if kv is not None:
                key, raw_value = kv
                if raw_value == '|-':
                    multiline_key = key
                    proxy[key] = ''
                else:
                    proxy[key] = _parse_yaml_scalar(raw_value)
            idx += 1
            continue

        # -- inside a proxy entry ------------------------------------------
        if proxy is not None:
            # Multiline continuation (6-space indent)
            if multiline_key is not None:
                if leading >= 6:
                    content = raw[6:].rstrip()
                    proxy[multiline_key] += content + '\n'
                    idx += 1
                    continue
                _close_multiline()
                # fall through to re-process this line as a new key:value

            # Key-value line: 4-space indent minimum
            rest = line.lstrip()
            kv = _find_colon_split(rest)
            if kv is not None:
                key, raw_value = kv
                if raw_value == '|-':
                    multiline_key = key
                    proxy[key] = ''
                else:
                    proxy[key] = _parse_yaml_scalar(raw_value)
                idx += 1
                continue

        idx += 1

    _close_multiline()
    if proxy is not None:
        proxies.append(proxy)

    return proxies


# ---------------------------------------------------------------------------
# YAML rendering
# ---------------------------------------------------------------------------

def format_yaml_scalar(value: Any) -> str:
    """Format a Python value as a YAML scalar (mirrors ``enrich_maxmind.py``)."""
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if value is None:
        return 'null'
    return str(value)


def _render_proxy_block(proxy: Dict[str, Any], latency: Optional[int] = None) -> List[str]:
    """Render a single proxy dict as indented YAML lines.

    When *latency* is provided a comment line ``# latency: XXXms`` is
    prepended.
    """
    lines: List[str] = []
    if latency is not None:
        lines.append(f'  # latency: {latency}ms')
    items = list(proxy.items())
    for idx, (key, value) in enumerate(items):
        prefix = '  -' if idx == 0 else '   '
        if isinstance(value, str) and '\n' in value:
            lines.append(f'{prefix} {key}: |-')
            lines.extend(f'      {line}' for line in value.splitlines())
        else:
            lines.append(f'{prefix} {key}: {format_yaml_scalar(value)}')
    return lines


def render_batch_config(
    proxies: List[Dict[str, Any]],
    controller_port: int,
    mixed_port: int,
) -> str:
    """Render a complete mihomo config YAML for one batch.

    The config includes a ``url-test`` proxy-group named ``test`` so that
    the external API can be used to trigger delay tests on all proxies at
    once.
    """
    proxy_names = [p['name'] for p in proxies]

    # We produce the YAML manually to match the project convention and avoid
    # introducing a PyYAML dependency.
    parts: List[str] = []
    parts.append(f'mixed-port: {mixed_port}')
    parts.append(f'external-controller: {format_yaml_scalar(f"127.0.0.1:{controller_port}")}')
    parts.append('allow-lan: false')
    parts.append('mode: Rule')
    parts.append('log-level: silent')
    parts.append('')

    # proxy-groups
    parts.append('proxy-groups:')
    parts.append('  - name: test')
    parts.append('    type: url-test')
    parts.append('    proxies:')
    for pn in proxy_names:
        parts.append(f'      - {format_yaml_scalar(pn)}')
    parts.append(f'    url: {format_yaml_scalar("https://www.gstatic.com/generate_204")}')
    parts.append('    interval: 10')
    parts.append('')

    # proxies
    parts.append('proxies:')
    for proxy in proxies:
        parts.extend(_render_proxy_block(proxy))
    parts.append('')

    return '\n'.join(parts)


def render_alive_yaml(
    proxies_with_latency: List[Tuple[Dict[str, Any], int]],
) -> str:
    """Render the ``--alive-mihomo`` output with latency comments."""
    lines: List[str] = ['proxies:']
    for proxy, latency in proxies_with_latency:
        lines.extend(_render_proxy_block(proxy, latency=latency))
    return '\n'.join(lines) + '\n'


