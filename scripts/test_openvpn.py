# Mihomo external API helpers
# ---------------------------------------------------------------------------

def _api_get(
    path: str,
    controller_port: int,
    timeout: float = DEFAULT_REQUEST_TIMEOUT,
) -> Optional[Any]:
    """GET *path* from the mihomo external controller API.

    Returns the decoded JSON response on success or ``None`` on any
    network / HTTP / parse error.
    """
    url = f'http://127.0.0.1:{controller_port}{path}'
    try:
        req = urllib.request.Request(url)
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return json.loads(resp.read().decode('utf-8'))
    except (urllib.error.URLError, urllib.error.HTTPError,
            socket.timeout, json.JSONDecodeError) as exc:
        logger.debug('API GET %s failed: %s', path, exc)
        return None


def wait_for_api(
    controller_port: int,
    timeout: float = DEFAULT_BATCH_TIMEOUT,
) -> bool:
    """Poll the mihomo API until it responds or *timeout* is reached."""
    deadline = time.time() + timeout
    poll_interval = 1.0

    while time.time() < deadline:
        result = _api_get('/proxies', controller_port, timeout=2)
        if result is not None and isinstance(result, dict):
            logger.info('Mihomo API ready on port %d', controller_port)
            return True
        time.sleep(poll_interval)

    logger.warning('Mihomo API did not become ready within %.0fs', timeout)
    return False


def run_delay_test(
    controller_port: int,
    timeout: float = DEFAULT_BATCH_TIMEOUT,
) -> Optional[Dict[str, int]]:
    """Trigger a delay test on the ``test`` proxy-group.

    Returns a mapping ``{proxy_name: latency_ms}`` for every proxy that
    responded within the per-request timeout.
    """
    url_param = urllib.parse.quote('https://www.gstatic.com/generate_204')
    path = f'/group/test/delay?url={url_param}&timeout=10000'

    deadline = time.time() + timeout
    last_result: Any = None

    while time.time() < deadline:
        result = _api_get(path, controller_port, timeout=12)
        if result is not None:
            if isinstance(result, dict):
                delays: Dict[str, int] = {}
                for name, delay_val in result.items():
                    if isinstance(delay_val, (int, float)) and delay_val > 0:
                        delays[name] = int(delay_val)
                if delays:
                    logger.info(
                        'Delay test completed: %d proxies responded',
                        len(delays),
                    )
                    return delays
                last_result = result
        time.sleep(1)

    if isinstance(last_result, dict):
        logger.warning(
            'Delay test returned but no positive delays (got %s)',
            last_result,
        )
        return last_result

    logger.warning('Delay test returned no results within %.0fs', timeout)
    return None


