"""
Test OpenVPN servers using mihomo's native Go OpenVPN implementation via Docker.

Parses the mihomo OpenVPN YAML config (produced by enrich_maxmind.py), batches
proxies, runs them through ephemeral mihomo Docker containers, collects latency
results via the mihomo external API, and annotates the original VPN Gate
data.json with test outcomes.

No root / TUN device required because mihomo's Go OpenVPN implementation does
not create a system network interface.

Output files:
  --tested-data    data.json with a ``test`` field on each server + top-level
                   ``test`` metadata section
  --alive-mihomo   mihomo YAML containing only alive proxies, sorted by latency,
                   with ``# latency: XXXms`` comments
  --results-json   summary JSON with all statistics and per-proxy results
"""

