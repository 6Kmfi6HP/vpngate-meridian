def extract_hostname(proxy_name: str) -> str:
    """Extract the hostname portion from a mihomo proxy name.

    Proxy names are formatted as ``COUNTRY AS<num> hostname`` by
    ``enrich_maxmind.py``.  The hostname is always the last token.

    Example::

        >>> extract_hostname("JP AS2516 vpn.example.test")
        "vpn.example.test"
    """
    return proxy_name.rsplit(' ', 1)[-1] if ' ' in proxy_name else proxy_name


def build_proxy_to_server_map(
    servers: List[Dict[str, Any]],
    proxy_names: List[str],
) -> Dict[str, int]:
    """Map each mihomo proxy name to its index in the *servers* list.

    The lookup uses the hostname derived from the proxy name.
    Unmatched proxies are logged and omitted.
    """
    hostname_to_idx: Dict[str, int] = {}
    for idx, server in enumerate(servers):
        hostname = (
            server.get('hostname')
            or server.get('name')
            or server.get('ip')
        )
        if hostname:
            hostname_to_idx[hostname] = idx

    proxy_to_server: Dict[str, int] = {}
    for pname in proxy_names:
        hostname = extract_hostname(pname)
        idx = hostname_to_idx.get(hostname)
        if idx is not None:
            proxy_to_server[pname] = idx
        else:
            logger.warning(
                'Could not match proxy %r to any server (hostname=%r)',
                pname, hostname,
            )

    return proxy_to_server


