def check_docker() -> bool:
    """Return ``True`` iff Docker is available and the daemon is running."""
    try:
        result = subprocess.run(
            ['docker', 'info', '--format', '{{.ServerVersion}}'],
            capture_output=True,
            text=True,
            timeout=10,
        )
        return result.returncode == 0
    except (subprocess.TimeoutExpired, FileNotFoundError):
        return False


def start_mihomo_container(
    config_path: str,
    batch_index: int,
    image: str,
    controller_port: int,
) -> Tuple[str, str]:
    """Start a mihomo Docker container, return ``(container_id, name)``."""
    container_name = f'mihomo-test-{os.getpid()}-batch{batch_index}'
    cmd = [
        'docker', 'run', '-d', '--rm',
        '--name', container_name,
        '--network', 'host',
        '-v', f'{os.path.abspath(config_path)}:/root/.config/mihomo/config.yaml',
        image,
    ]
    logger.info(
        'Starting mihomo container %s for batch %d ...',
        container_name, batch_index,
    )
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
    if result.returncode != 0:
        raise RuntimeError(
            f'Docker run failed (exit {result.returncode}): '
            f'{result.stderr.strip()}'
        )
    container_id = result.stdout.strip()
    logger.info(
        'Container %s started (%s...)',
        container_name, container_id[:12],
    )
    return container_id, container_name


def stop_mihomo_container(container_name: str) -> None:
    """Forcefully stop (``docker kill``) and wait for removal (``--rm``)."""
    try:
        subprocess.run(
            ['docker', 'kill', container_name],
            capture_output=True,
            text=True,
            timeout=15,
        )
        # Wait for the --rm flag to finish removal
        subprocess.run(
            ['docker', 'wait', container_name],
            capture_output=True,
            text=True,
            timeout=15,
        )
    except subprocess.TimeoutExpired:
        logger.warning('Timeout stopping container %s', container_name)
    except Exception as exc:
        logger.warning('Error stopping container %s: %s', container_name, exc)


